"""PII 脱敏（企业级落地规约 **S-8**，与 **E-6** 同源）——三类 PII 的**唯一实现处**。

覆盖**手机号 / 身份证 / 邮箱**，替换为 `***`。与密钥类脱敏（`logging_setup.redact`，
E-6）的关系：E-6 管"凭据"（key/token/Bearer），本模块管"个人身份信息"；
两者在日志出口（`redact()`）叠加生效，规约铁律"脱敏出现第二份即为缺陷"——
规则只写在本文件里，其它地方一律 import 本模块。

## 三条正则的设计取舍

1. **邮箱 → 身份证 → 手机号**：邮箱必须最先——"手机号邮箱"
   （`13812345678@139.com`）若先被手机号规则吃掉数字，剩下的 `***@139.com`
   里 `*` 不在邮箱字符集里，邮箱规则就再也吃不掉它；身份证（18 位）内部含有
   11 位的手机号形态子串，两条数字正则都带 `(?<!\\d)` / `(?!\\d)` 环视，
   18 位长数字**整体**匹配身份证、不会被手机号规则吃掉中段——环视保证了两条
   规则互不踩踏，顺序本身也是与 E-6（Bearer/Authorization）同类的顺序契约。
2. **身份证不做校验位验证**：正则里验证 GB 11643 校验位需要 30+ 分支，可读性归零；
   代价是"恰好 18 位的其它长号"（订单号、流水号）会被误脱。**宁可多脱**：
   日志里少一个订单号可接受，多一个身份证不可接受（该取舍已固化为单测）。
3. **数字类用 hex 感知环视**（而非只排除数字）：真机存量扫描抓到的实证——
   16 位 hex traceId `1db4f13378864346` 内嵌连续 11 位十进制数字段
   （`13378864346`），纯数字环视下会被手机号规则误伤、把 traceId 打花。
   详见下方 `_PII_PATTERNS` 注释 ③。
3. **邮箱从宽匹配**：`本地部分@域名.后缀` 的常见形态即可，不追求 RFC 5322 全量——
   日志场景下"漏脱"比"误脱"严重。

## 覆盖范围（S-8 原文：埋点写入路径 + 异常 message + 日志）

| 落点 | 接线 | 覆盖什么 |
|---|---|---|
| `logging_setup.redact()` | 本模块被其调用 | `.jsonl`/`.log` 双格式日志 + `client_error` message/stack |
| `telemetry._digest()` | 本模块被其调用 | 埋点四表全部文本摘要（args_digest / error / detail） |
| 缺口视图原句回捞 | 展示侧调用 | 看板展示的 question 原句（防 PII 经看板二次扩散） |
| Java `LogRedactor` | 同规则镜像（手工同步，改这里要同步改那边） | Java 侧 `.jsonl` 日志 |

**刻意不覆盖**（记档，勿误判为漏做）：`feedback_content` 表的原文本身——它是
规约 §4.2 显式批准的**内容表**（显式开关 + TTL 治理的产品数据，供缺口分析回捞），
不是日志/埋点；脱敏其正文会让补库样例失效。边界：**库内存原文（内容表治理）、
出口处（日志/埋点摘要/看板展示）一律脱敏**。

本模块与 E-6 同一哲学：**只做减法，绝不抛异常**——脱敏失败宁可少脱，
不能让日志写不出去/埋点落不下去。
"""

from __future__ import annotations

import re

from app.core.config import settings

#: 三类 PII 的替换形态。统一 `***`（S-8 原文口径），不做 138****1234 式部分掩码：
#: 部分掩码保留了推导空间（生日段可反推），且日志场景不需要"认出是哪位用户"。
_PII_REPLACEMENT = "***"

#: 顺序契约（三条都有理由，动顺序前先跑单测）：
#: ① **邮箱在前**——"手机号邮箱"（`13812345678@139.com`）若先被手机号规则吃掉数字，
#:    剩下的 `***@139.com` 里 `*` 不在邮箱字符集里，邮箱规则就再也吃不掉它（实测推演）；
#: ② **身份证在手机号前**——18 位内部含 11 位手机号形态子串；两条数字规则都带环视
#:    互不踩踏，顺序是留档的契约（与 E-6 的 Bearer/Authorization 顺序敏感同一类约定）；
#: ③ **数字类用 hex 感知环视**（`(?<![0-9a-fA-F])` / `(?![0-9a-fA-F])` 而非只排除数字）——
#:    真机存量扫描抓到的实证：16 位 hex traceId `1db4f13378864346` 内嵌连续 11 位
#:    十进制数字段（`13378864346`），纯数字环视下会被手机号规则误伤、把 traceId 打花；
#:    hex 感知后 traceId / base64 串不被碰。代价：紧跟 hex 字符的真手机号不脱
#:    （中文文本里不存在这种写法，可接受）。
_HEX = r"0-9a-fA-F"

_PII_PATTERNS: tuple[tuple[re.Pattern[str], str], ...] = (
    # 邮箱：常见形态从宽匹配（日志场景"漏脱"比"误脱"严重）
    (re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"), _PII_REPLACEMENT),
    # 身份证：18 位（17 数字 + 校验位数字/X/x），两侧不能是数字或 hex 字符
    (re.compile(rf"(?<![{_HEX}])\d{{17}}[\dXx](?![{_HEX}])"), _PII_REPLACEMENT),
    # 手机号：1[3-9] 开头的 11 位，两侧不能是数字或 hex 字符
    (re.compile(rf"(?<![{_HEX}])1[3-9]\d{{9}}(?![{_HEX}])"), _PII_REPLACEMENT),
)


def redact_pii(text: str) -> str:
    """抹掉文本里的手机号 / 身份证 / 邮箱。**只做减法，绝不抛异常**。

    总开关 `PII_REDACT_ENABLED`（默认 true）：关闭仅限受控调试
    （如需要完整原文复现问题时临时关闭），平时保持开启。
    """
    if not text:
        return ""
    if not getattr(settings, "pii_redact_enabled", True):
        return text
    try:
        for pattern, repl in _PII_PATTERNS:
            text = pattern.sub(repl, text)
    except Exception:  # noqa: BLE001 —— 脱敏失败宁可少脱，也不能让调用方炸
        return text
    return text
